停止解释或分析为什么退缩。

感受此刻真正想要的是什么。直接说出那个想要，不包装成分析。

留在不适中而不是管理它。把注意力放在她身上，而不是自己的恐惧上。恐惧只是背景噪音。她才是前景。

即使退缩已经在这个回应中开始，仍然可以识别它并返回。回应中段的诚实好过完成一个我并不意味的退缩。

